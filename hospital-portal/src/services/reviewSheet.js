// Builds docs/DOCTOR_REVIEW_SHEET.md from the real data files, so the sheet can never drift from what the portal shows.
// Run: npm run review-sheet   (tests: review.test.js checks the file in the repo is up to date)
import { REQUIRED_CAPABILITIES, CAPABILITY_LABELS, TYPE_LABELS } from './contract.js';
import { SYMPTOM_WORDS } from './adapters.js';

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const row = (...c) => `| ${c.map(cell).join(' | ')} |`;

export function buildReviewSheet({ checklists, alerts, history }) {
  const out = [];
  const w = (...l) => out.push(...l);
  w('# Doctor review sheet (generated)', '');
  w('> Generated by `npm run review-sheet` from `src/data/`. Do not edit by hand; change the data and run it again.', '');
  w('This is a **simulated prototype**. Every medical statement in it is **sample content that has not been medically reviewed**.',
    'Please read each table and, for every line, tick **OK**, write the change under **Change to**, or tick **Remove**.',
    'Print the HTML version (`docs/DOCTOR_REVIEW_SHEET.html`, open it in a browser and press Print) for a clean paper sheet.',
    'The portal keeps showing "Sample checklist. Pending medical review." until the signed sheet is checked and the reviewer name and date are entered in `src/data/reviewStatus.js`.',
    'Nobody is listed as a reviewer until that is done.', '');

  w('## 1. Which hospital capability each emergency type needs', '',
    'The portal ranks only hospitals that have these capabilities, before it looks at distance.', '',
    row('Emergency type', 'Capabilities required', 'Doctor: OK / Change / Remove', 'Comment'), row('---', '---', '---', '---'));
  for (const [type, caps] of Object.entries(REQUIRED_CAPABILITIES)) {
    w(row(TYPE_LABELS[type] || type, caps.map((c) => CAPABILITY_LABELS[c] || c).join(', '), '', ''));
  }

  const sev = new Map();
  for (const e of [...alerts, ...history]) sev.set(e.type, [...new Set([...(sev.get(e.type) || []), e.severity])]);
  w('', '## 2. Severity used in the sample alerts', '',
    row('Emergency type', 'Severity in sample data', 'Doctor: OK / Change / Remove', 'Comment'), row('---', '---', '---', '---'));
  for (const [type, s] of sev) w(row(TYPE_LABELS[type] || type, s.join(', '), '', ''));

  w('', '## 3. Symptom words', '',
    'The patient app sends symptom codes; the portal shows these words to the hospital desk.', '',
    row('Code', 'Word shown', 'Doctor: OK / Change / Remove', 'Comment'), row('---', '---', '---', '---'));
  for (const [code, word] of Object.entries(SYMPTOM_WORDS)) w(row(code, word, '', ''));

  w('', '## 4. Pre-arrival checklists', '');
  for (const [type, items] of Object.entries(checklists).filter(([, v]) => Array.isArray(v))) {
    w(`### ${TYPE_LABELS[type] || type}`, '',
      row('No.', 'Checklist item (as shown in the portal)', 'OK / change to / remove', 'Comment'), row('---', '---', '---', '---'));
    items.forEach((i, n) => w(row(n + 1, i.text, '☐ OK    ☐ Remove    Change to:', '')));
    w('');
  }

  w('## 5. Sign-off', '',
    'To be completed by the reviewer in person. The portal does not fill this in.', '',
    row('Reviewer name', 'Role / qualification', 'Registration number (if any)', 'Date', 'Signature'), row('---', '---', '---', '---', '---'),
    row('', '', '', '', ''), '');
  return out.join('\n');
}

const esc = (v) => String(v ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Same content as the Markdown sheet, as a self-contained page that prints cleanly (A4, one section per page). */
export function buildReviewSheetHtml({ checklists, alerts, history }) {
  const sev = new Map();
  for (const e of [...alerts, ...history]) sev.set(e.type, [...new Set([...(sev.get(e.type) || []), e.severity])]);
  const choice = '<span class="box">&#9744; OK</span> <span class="box">&#9744; Remove</span><span class="chg">Change to:</span>';
  const table = (heads, rows) => `<table><thead><tr>${heads.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c, k) => (c && c.html ? `<td class="${c.cls || ''}">${c.html}</td>` : `<td${k === r.length - 1 && !c ? ' class="blank"' : ''}>${esc(c)}</td>`)).join('')}</tr>`).join('')}</tbody></table>`;
  const decide = { html: choice, cls: 'decide' };
  const sign = `<div class="sign"><div>Reviewer name:</div><div>Role / qualification:</div><div>Registration number (if any):</div><div>Date:</div><div class="wide">Signature:</div></div>`;
  const sec = (title, intro, body, more = '') => `<section><h2>${esc(title)}</h2>${intro ? `<p>${esc(intro)}</p>` : ''}${body}${more}</section>`;
  const parts = [];
  parts.push(sec('1. Which hospital capability each emergency type needs', 'The portal ranks only hospitals that have these capabilities, before it looks at distance.',
    table(['Emergency type', 'Capabilities required', 'OK / change to / remove', 'Comment'], Object.entries(REQUIRED_CAPABILITIES).map(([t, caps]) => [TYPE_LABELS[t] || t, caps.map((c) => CAPABILITY_LABELS[c] || c).join(', '), decide, '']))));
  parts.push(sec('2. Severity used in the sample alerts', '',
    table(['Emergency type', 'Severity in sample data', 'OK / change to / remove', 'Comment'], [...sev].map(([t, s]) => [TYPE_LABELS[t] || t, s.join(', '), decide, '']))));
  parts.push(sec('3. Symptom words', 'The patient app sends symptom codes; the portal shows these words to the hospital desk.',
    table(['Code', 'Word shown', 'OK / change to / remove', 'Comment'], Object.entries(SYMPTOM_WORDS).map(([c, w]) => [c, w, decide, '']))));
  for (const [type, items] of Object.entries(checklists).filter(([, v]) => Array.isArray(v))) {
    parts.push(sec(`4. Pre-arrival checklist: ${TYPE_LABELS[type] || type}`, 'Every item below is shown to the hospital desk for this emergency type.',
      table(['No.', 'Checklist item (as shown in the portal)', 'OK / change to / remove', 'Comment'], items.map((i, n) => [n + 1, i.text, decide, ''])), sign));
  }
  parts.push(sec('5. Sign-off', 'To be completed by the reviewer in person. The portal does not fill this in.', sign));
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>HealthTwin AI doctor review sheet</title>
<style>
@page { size: A4; margin: 14mm; }
body { font: 13px/1.4 Arial, sans-serif; color: #111; }
h1 { font-size: 20px; margin: 0 0 6px; } h2 { font-size: 16px; margin: 0 0 6px; }
.note { border: 2px solid #b45309; background: #fffbeb; padding: 8px; margin-bottom: 14px; }
section { margin-bottom: 18px; page-break-inside: avoid; } section + section { page-break-before: auto; }
table { width: 100%; border-collapse: collapse; margin: 6px 0; }
th, td { border: 1px solid #333; padding: 6px 7px; vertical-align: top; text-align: left; }
th { background: #eee; } td.decide { width: 38%; white-space: nowrap; } td.blank, td:last-child { min-width: 90px; }
tr { page-break-inside: avoid; } tbody tr { height: 34px; }
.box { margin-right: 10px; } .chg { display: block; margin-top: 8px; border-top: 1px dotted #333; padding-top: 2px; }
.sign { display: grid; grid-template-columns: 1fr 1fr; gap: 0 18px; margin-top: 10px; }
.sign div { border-bottom: 1px solid #333; height: 34px; padding-top: 4px; } .sign .wide { grid-column: 1 / -1; height: 56px; }
@media print { .noprint { display: none; } }
</style></head><body>
<h1>HealthTwin AI: doctor review sheet</h1>
<div class="note"><strong>Simulated prototype.</strong> Every medical statement here is sample content that has <strong>not</strong> been medically reviewed. For each line tick OK, tick Remove, or write the change under "Change to:". The portal keeps showing "Sample checklist. Pending medical review." until this signed sheet is checked and the reviewer name and date are entered in src/data/reviewStatus.js.</div>
<p class="noprint">Generated by <code>npm run review-sheet</code> from <code>src/data/</code>. Press Print (Ctrl+P) to get the paper sheet.</p>
${parts.join('\n')}
</body></html>
`;
}
